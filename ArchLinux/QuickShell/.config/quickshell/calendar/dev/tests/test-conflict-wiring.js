const assert = require("node:assert/strict")
const fs = require("node:fs")
const path = require("node:path")

const root = path.join(__dirname, "../..")
const service = fs.readFileSync(path.join(root, "services/CalendarConflictService.qml"), "utf8")
const calendarService = fs.readFileSync(path.join(root, "services/CalendarService.qml"), "utf8")
const window = fs.readFileSync(path.join(root, "ui/CalendarWindow.qml"), "utf8")
const panel = fs.readFileSync(path.join(root, "ui/ConflictResolutionPanel.qml"), "utf8")
const eventCard = fs.readFileSync(path.join(root, "ui/EventCard.qml"), "utf8")
const broker = fs.readFileSync(path.join(root, "parse/conflict-broker.sh"), "utf8")

assert.match(service, /conflict-select/)
assert.doesNotMatch(service, /conflictProcess/)
assert.doesNotMatch(service, /clearProcess/)
assert.match(broker, /conflict-clear/)
assert.match(service, /root\.brokerPath, "resolve", "personal"/)
assert.match(service, /watchChanges: true/)
assert.match(service, /exitCode === 3[\s\S]*Conflict resolved, but pimsync could not restart/)
assert.doesNotMatch(service, /sh", "-c"/)
assert.match(calendarService, /syncBrokerPath/)
assert.doesNotMatch(service, /Timer \{/)
assert.match(calendarService, /CalendarConflictService/)
assert.match(calendarService, /Resolve calendar conflict before editing this event/)
assert.match(window, /property bool conflictOpen: false/)
assert.match(window, /alert: root\.calendarService\.conflictService\.hasConflict/)
assert.match(window, /ConflictResolutionPanel/)
assert.match(window, /root\.openConflicts\(\)/)
assert.match(window, /alertCount: root\.calendarService\.conflictService\.conflicts\.length/)
assert.match(window, /text: button\.alertCount > 99 \? "99\+"/)
assert.match(eventCard, /property bool conflicted: false/)
assert.match(eventCard, /visible: root\.conflicted/)
assert.match(eventCard, /text: "!"/)
assert.match(panel, /Confirm/)
assert.match(panel, /Cancel/)
assert.match(panel, /selectedSide/)
assert.match(panel, /confirmHover/)
assert.match(panel, /cancelHover/)
assert.match(panel, /PointingHandCursor/)
assert.match(panel, /cursorShape: enabled \? Qt\.PointingHandCursor : Qt\.ArrowCursor/)
assert.match(panel, / of /)
assert.match(panel, /Unknown ICS properties stay unchanged/)
assert.doesNotMatch(window, /notify|notification/i)
console.log("Conflict wiring tests passed")
